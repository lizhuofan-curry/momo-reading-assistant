if (await page.locator("#max-words").inputValue() !== "20") throw new Error("最多提取下拉没有同步值");
await page.locator(".pretty-select:has(#expansion) .select-trigger").click();
await page.locator(".pretty-select:has(#expansion) .select-option", { hasText: "附带派生词与短语" }).click();
if (await page.locator("#expansion").inputValue() !== "full") throw new Error("词汇扩展选项没有同步值");
const ocrImage = await page.evaluate(() => {
  const canvas = document.createElement("canvas");
  canvas.width = 1600;
  canvas.height = 480;
  const context = canvas.getContext("2d");
  context.fillStyle = "white";
  context.fillRect(0, 0, canvas.width, canvas.height);
  context.fillStyle = "black";
  context.font = "700 76px Arial";
  context.fillText("Robust temporal representations", 70, 170);
  context.fillText("improve model generalization.", 70, 300);
  return canvas.toDataURL("image/png").split(",")[1];
});
await page.locator("#file-input").setInputFiles({ name: "reading-note.png", mimeType: "image/png", buffer: Buffer.from(ocrImage, "base64") });
if (!await page.locator("#image-preview").isVisible()) throw new Error("图片预览未显示");
await page.locator("#extract-file").click();
try {
  await page.locator("#file-result.success").waitFor({ state: "visible", timeout: 90000 });
} catch (error) {
  throw new Error(`本地 OCR 超时：${await page.locator("#file-result").textContent()}；浏览器错误：${[...consoleErrors, ...pageErrors].join(" | ") || "无"}`, { cause: error });
}
if (!/robust/i.test(await page.locator("#source-text").inputValue())) throw new Error("本地 OCR 未识别示例英文");
await page.screenshot({ path: fileURLToPath(new URL("online-image-ocr.png", output)), fullPage: true });
await page.locator("#quota-badge").click();
if (!await page.locator("#quota-panel").isVisible()) throw new Error("免费规则说明未展开");
if (!await page.locator("#quota-panel").getByText(/连续 7×24 小时内不限分析次数/).isVisible()) throw new Error("免费规则不完整");
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "查看结果示例" }).click();
if (await page.locator(".word-entry").count() < 3) throw new Error("免登录示例未渲染");
if (!await page.locator(".word-expansion").first().isVisible()) throw new Error("派生词与短语扩展未显示");
await page.locator(".word-expansion").first().locator("summary").click();
if (!await page.locator(".word-expansion").first().getByText("robustness", { exact: true }).isVisible()) throw new Error("词族内容未展开");
if (!await page.locator("#result-status.success").isVisible()) throw new Error("结果成功状态未显示");
await page.locator("#token-help").click();
if (!await page.locator("#token-explainer").getByText(/只分析和审核生词不需要 Token/).isVisible()) throw new Error("Token 说明未展开");
for (const path of ["/guide/", "/privacy/", "/help/", "/connections/"]) {
  const child = await context.newPage();
  child.on("pageerror", error => pageErrors.push(`${path}: ${error.message}`));
  await child.goto(new URL(path, baseUrl).href, { waitUntil: "networkidle" });
  if (!(await child.locator("main").innerText()).trim()) throw new Error(`${path} 页面为空`);
  await child.close();
}
const connectionPage = await context.newPage();
await connectionPage.route("**/api/models", route => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ ok: true, provider: "Google Gemini", models: [{ id: "gemini-3.7-flash", name: "Gemini 3.7 Flash" }, { id: "gemini-3.7-pro", name: "Gemini 3.7 Pro" }] }) }));
await connectionPage.route("**/api/test-ai", route => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ ok: true, message: "Google Gemini · gemini-3.7-pro 连接成功" }) }));
await connectionPage.route("**/api/test-maimemo", route => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ ok: true, message: "墨墨 Token 连接成功" }) }));
await connectionPage.goto(new URL("/connections/", baseUrl).href, { waitUntil: "networkidle" });
await connectionPage.locator("#provider-trigger").click();
if (await connectionPage.locator(".provider-option").count() !== 15) throw new Error("服务商数量不是 15 家");
await connectionPage.screenshot({ path: fileURLToPath(new URL("connections-providers.png", output)), fullPage: true });
await connectionPage.locator('[data-provider="gemini"]').click();
if (await connectionPage.locator("#provider-name").textContent() !== "Google Gemini") throw new Error("自定义服务商下拉选择失败");
if (await connectionPage.locator("#api-key-link").getAttribute("href") !== "https://aistudio.google.com/app/apikey") throw new Error("API Key 官方入口未随服务商切换");
if (await connectionPage.locator("#api-key-link").getAttribute("target") !== "_blank") throw new Error("API Key 官方入口没有在新标签页打开");
await connectionPage.locator("#api-key").fill("test-api-key");
