if (savedProvider !== "gemini") throw new Error("测试成功后未保存所选服务商");
await connectionPage.locator("#model-trigger").click();
await connectionPage.locator('[data-model="gemini-3.7-flash"]').click();
const switchedModel = await connectionPage.evaluate(() => JSON.parse(localStorage.getItem("momo_ai_config") || "null")?.model);
if (switchedModel !== "gemini-3.7-flash") throw new Error("切换模型后没有立即持久保存");
