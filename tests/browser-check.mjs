await page.locator(".pretty-select:has(#level) .select-trigger").click();
await page.locator(".pretty-select:has(#level) .select-option", { hasText: "基础入门（A1）" }).click();
if (await page.locator("#level").inputValue() !== "基础入门（A1）") throw new Error("基础水平选项没有同步值");
await page.locator(".pretty-select:has(#level) .select-trigger").click();
await page.locator(".pretty-select:has(#level) .select-option", { hasText: "自定义学习水平" }).click();
if (!await page.locator("#custom-level-field").isVisible()) throw new Error("自定义水平输入框未显示");
