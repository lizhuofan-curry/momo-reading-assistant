await connectionPage.getByText(/已自动识别 2 个模型/).waitFor({ state: "visible" });
await connectionPage.locator("#model-trigger").click();
await connectionPage.locator("#model-search").fill("pro");
await connectionPage.screenshot({ path: fileURLToPath(new URL("connections-models.png", output)), fullPage: true });
await connectionPage.locator('[data-model="gemini-3.7-pro"]').click();
await connectionPage.locator("#test-ai").click();
await connectionPage.getByText("Google Gemini · gemini-3.7-pro 连接成功", { exact: true }).waitFor({ state: "visible" });
